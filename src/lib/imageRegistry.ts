/** Ordered storefront gallery. Never the customizer overlay bases except the dedicated blank back. */
export function galleryShots(id: CanonicalProductId): GalleryShot[] {
  if (id === "two-tone-cap") return TWO_TONE_CAP_GALLERY;
  if (id === "area-code-cap") return AREA_CODE_CAP_GALLERY;
  if (id === "heritage-jersey") return MATCH_JERSEY_GALLERY;
  if (id === "match-short") return MATCH_SHORT_GALLERY;
  if (id === "performance-set") return PERFORMANCE_SET_GALLERY;
  if (id === "performance-ls") return PERFORMANCE_LS_GALLERY;
  if (id === "performance-short") return PERFORMANCE_SHORT_GALLERY;
  if (id === "performance-ls-mens") return PERFORMANCE_LS_MENS_GALLERY;
  if (id === "performance-ls-womens") return PERFORMANCE_LS_WOMENS_GALLERY;
  if (id === "performance-short-mens") return PERFORMANCE_SHORT_MENS_GALLERY;
  if (id === "performance-short-womens") return PERFORMANCE_SHORT_WOMENS_GALLERY;
  if (id === "performance-set-mens") return PERFORMANCE_SET_MENS_GALLERY;
  if (id === "performance-set-womens") return PERFORMANCE_SET_WOMENS_GALLERY;
  if (id === "travel-set") return TRAVEL_SET_GALLERY;
  if (id === "max-heavy-full-zip") return MAX_HEAVY_FULL_ZIP_GALLERY;
  if (id === "max-heavy-sweatpant") return MAX_HEAVY_SWEATPANT_GALLERY;
  if (id === "gothic-b-beanie") return GOTHIC_B_BEANIE_BLACK_GALLERY;
  if (id === "gothic-b-beanie-brown") return GOTHIC_B_BEANIE_BROWN_GALLERY;
  if (id === "harbor-coach") return HARBOR_COACH_GALLERY;
  if (id === "harbor-pullover") return HARBOR_PULLOVER_GALLERY;
  if (id === "harbor-sweatpant-grey") return HARBOR_SWEATPANT_GREY_GALLERY;
  if (id === "harbor-sweatpant-black") return HARBOR_SWEATPANT_BLACK_GALLERY;
  if (id === "nb-bbp400") return NB_P400_GALLERY;
  if (id === "nb-p400-chalk") return NB_P400_CHALK_GALLERY;
  if (id === "nb-p400-volt") return NB_P400_VOLT_GALLERY;
  if (id === "nb-runner") return NB_RUNNER_GALLERY;
  if (id === "nb-runner-heat") return NB_RUNNER_HEAT_GALLERY;
  if (id === "nb-runner-cardinal") return NB_RUNNER_CARDINAL_GALLERY;
  const set = IMAGE_REGISTRY[id];
  if (set.pending) return [];
  const views = campaignViews(id);
  const pair = platePair(id);
  const seen = new Set<string>();
  const shots: GalleryShot[] = [];
  for (const src of [views.front, views["three-quarter"], views.back, pair.front, pair.secondary]) {
    if (!src || seen.has(src)) continue;
    seen.add(src);
    shots.push({ src, alt: "" });
  }
  return shots;
}

export { matchJerseyBackBlank, matchJerseyFrontMarks };

export function imagesFor(id: CanonicalProductId): ProductImageSet {
  return IMAGE_REGISTRY[id];
}

export function platePair(id: CanonicalProductId): { front: string; secondary: string } {
  const set = IMAGE_REGISTRY[id];
  if (set.pending) {
    return { front: COMING_SOON, secondary: COMING_SOON };
  }
  const front = set.productFront ?? set.modelFront ?? COMING_SOON;
  const secondary = set.productBack ?? set.modelSecondary ?? front;
  return { front, secondary };
}

export function campaignViews(id: CanonicalProductId): {
  front?: string;
  back?: string;
  "three-quarter"?: string;
} {
  const set = IMAGE_REGISTRY[id];
  if (set.pending) return {};
  const front = set.modelFront ?? set.productFront;
  const back = set.modelSecondary ?? set.productBack;
  const extraThreeQuarter =
    set.productFront &&
    set.productFront !== front &&
    set.productFront !== back
      ? set.productFront
      : undefined;
  return {
    ...(front ? { front } : {}),
    ...(back ? { back } : {}),
    ...(extraThreeQuarter
      ? { "three-quarter": extraThreeQuarter }
      : front && front !== back
        ? { "three-quarter": front }
        : {}),
  };
}
